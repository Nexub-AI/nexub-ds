// Writes the docs preview manifest and the Maestro preview flow from one source:
//   src/preview/catalog.ts        → components, their web twins and example titles
//   src/app/patterns/[name].tsx   → screen patterns (the PATTERNS table)
// Outputs (committed, so the docs build doesn't need the mobile toolchain):
//   preview-manifest.json                  read by apps/docs at build time
//   .maestro/previews/previews.yaml        one screenshot per example, iOS + Android
// `--check` fails if either file is stale (runs in `pnpm test`).
//
// Run: node --experimental-strip-types scripts/preview-manifest.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG } from '../src/preview/catalog.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = '/m';

// PATTERNS rows look like:  name: { title: 'Title', subtitle: 'Subtitle', Component: X, … },
function readPatterns() {
  const src = readFileSync(join(root, 'src/app/patterns/[name].tsx'), 'utf8');
  const block = src.slice(src.indexOf('export const PATTERNS'));
  const rows = [...block.matchAll(/^\s+([a-z][\w-]*): \{ title: '([^']+)', subtitle: '([^']+)'/gm)];
  if (rows.length === 0) throw new Error('No rows found in PATTERNS (src/app/patterns/[name].tsx); update the parser.');
  return Object.fromEntries(rows.map(([, name, title, subtitle]) => [name, { title, subtitle, path: `${BASE}/preview/pattern/${name}` }]));
}

const components = Object.fromEntries(
  Object.entries(CATALOG).map(([slug, e]) => [
    slug,
    { title: e.title, kind: e.kind, web: e.web, examples: [...e.examples], path: `${BASE}/preview/${slug}` },
  ]),
);
const byWeb = {};
for (const [slug, e] of Object.entries(CATALOG)) if (e.web) (byWeb[e.web] ??= []).push(slug);
const patterns = readPatterns();

const manifest = {
  $comment: 'Generated by apps/mobile/scripts/preview-manifest.mjs. Do not edit.',
  version: 1,
  base: BASE,
  query: {
    ex: "'all' (default) or an example index",
    scheme: 'light | dark | system',
    brand: 'nexub | payub | bookub | leap | founderub',
    contrast: 'standard | medium | high | system',
  },
  messages: {
    toPreview: "{ type: 'nexub-theme', scheme?, brand?, contrast? } (same origin only)",
    fromPreview: "{ type: 'nexub-preview-size', height } (component previews)",
  },
  components,
  patterns,
  byWeb,
};

const flow = [
  '# Generated by apps/mobile/scripts/preview-manifest.mjs. Do not edit.',
  '# One screenshot per docs preview example: <slug>--<example>--<platform>.png',
  '# (patterns: pattern-<name>--<platform>.png). Deep links into /preview/….',
  '# iOS asks "Open in Nexub Mobile?" the first time a link opens the app, hence',
  '# the conditional tap after each link.',
  'appId: ai.nexub.mobile',
  '---',
  '- launchApp',
  '- extendedWaitUntil:',
  '    visible: "Components"',
  '    timeout: 60000',
];
// Screens that open a native modal on mount: the modal is its own window on
// Android, so Maestro can't see the screen's preview-ready marker underneath.
// Wait for text inside the modal instead.
const READY_TEXT = { 'pattern/apps': 'Nexub apps' };
const open = (link, shot) => {
  const text = READY_TEXT[link.replace(/^preview\//, '')];
  flow.push(
    `- openLink: nexub://${link}`,
    '- runFlow:',
    '    when:',
    '      visible: "Open"',
    '    commands:',
    '      - tapOn: "Open"',
    '- extendedWaitUntil:',
    ...(text ? [`    visible: "${text}"`] : ['    visible:', '      id: "preview-ready"']),
    '    timeout: 15000',
    '- waitForAnimationToEnd',
    `- takeScreenshot: ${shot}--\${maestro.platform}`,
  );
};
for (const [slug, e] of Object.entries(CATALOG)) {
  e.examples.forEach((_, i) => open(`preview/${slug}?ex=${i}`, `${slug}--${i}`));
}
for (const name of Object.keys(patterns)) open(`preview/pattern/${name}`, `pattern-${name}`);

const outputs = [
  [join(root, 'preview-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`],
  [join(root, '.maestro/previews/previews.yaml'), `${flow.join('\n')}\n`],
];

const check = process.argv.includes('--check');
let stale = 0;
for (const [file, content] of outputs) {
  if (check) {
    let current = '';
    try {
      current = readFileSync(file, 'utf8');
    } catch {}
    if (current !== content) {
      console.error(`Stale: ${file}. Run: pnpm --filter @nexub/mobile preview-manifest`);
      stale++;
    }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    console.log(`Wrote ${file}`);
  }
}
if (stale) process.exit(1);
