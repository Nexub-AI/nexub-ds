// Regenerates every brand file from the official master, assets/nexub-mark.svg
// (a verbatim copy of "5. Logos/Nexub Logo/icon_nexub.svg"). Run after the
// master or a glyph changes, and commit the output:
//
//   pnpm --filter @nexub/brand build:assets
//
// Writes:
//   assets/nexub-mark-mono.svg            single-colour mark (currentColor)
//   assets/app-icon[-<product>].svg       black glass tile + glyph
//   assets/app-icon[-<product>]-{192,512}.png
//   assets/favicon.ico                    16/32/48 from the Nexub tile
//   ../tokens/tokens/brand-mark.json      --color-brand-mark-1…n
//   ../icons/src/icons/nexubMarkData.ts   mark geometry for <NexubMark>/<Logo>
//   ../themes/src/base.css                .nxm-* stop classes (marked block)

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (p) => readFileSync(root + p, 'utf8');
const master = read('assets/nexub-mark.svg');

// Per-product tiles: same tile, different glyph. `glyph` is an SVG fragment in
// the 512×512 tile space (glyphs/<id>.svg); `halo` tints the glow behind it.
const MARK_GLYPH = `<svg x="97" y="148" width="318" height="228" viewBox="0 0 78 56">${inner(master)}</svg>`;
const PRODUCTS = [
  { id: '', glyph: MARK_GLYPH, halo: '#8b6cff' }, // app-icon.svg — the Nexub mark
  { id: 'account', glyph: read('glyphs/account.svg'), halo: '#4099f1' },
];

// ─── Parse the master ────────────────────────────────────────────────────────
const attr = (tag, name) => new RegExp(`\\s${name}="([^"]*)"`).exec(tag)?.[1];
const paths = [...master.matchAll(/<path\b[^>]*>/g)].map(([tag]) => ({
  d: attr(tag, 'd'),
  gradient: Number(/paint(\d+)_/.exec(attr(tag, 'fill'))[1]),
}));
const colors = [];
const gradients = [...master.matchAll(/<linearGradient\b([^>]*)>([\s\S]*?)<\/linearGradient>/g)].map(
  ([, head, body]) => ({
    x1: Number(attr(head, 'x1')),
    y1: Number(attr(head, 'y1')),
    x2: Number(attr(head, 'x2')),
    y2: Number(attr(head, 'y2')),
    stops: [...body.matchAll(/<stop\b[^>]*>/g)].map(([tag]) => {
      const hex = attr(tag, 'stop-color').toLowerCase();
      if (!colors.includes(hex)) colors.push(hex);
      const stop = { offset: Number(attr(tag, 'offset') ?? 0), color: colors.indexOf(hex) + 1 };
      const opacity = attr(tag, 'stop-opacity');
      if (opacity !== undefined) stop.opacity = Number(opacity);
      return stop;
    }),
  }),
);

// ─── Tokens + React data ─────────────────────────────────────────────────────
const tokenJson = {
  color: {
    brand: {
      mark: Object.fromEntries(colors.map((hex, i) => [i + 1, { $value: hex, $type: 'color' }])),
    },
  },
};
writeFileSync(`${root}../tokens/tokens/brand-mark.json`, `${JSON.stringify(tokenJson, null, 2)}\n`);

writeFileSync(
  `${root}../icons/src/icons/nexubMarkData.ts`,
  [
    '// Generated by packages/brand/scripts/build-assets.mjs from the official',
    '// Nexub mark. Do not edit. `color` n is the token --color-brand-mark-n.',
    `export const NEXUB_MARK_PATHS = ${JSON.stringify(paths, null, 2)} as const;`,
    '',
    `export const NEXUB_MARK_GRADIENTS = ${JSON.stringify(gradients, null, 2)} as const;`,
    '',
  ].join('\n'),
);

// Stop colours as classes (NexubMark's stopClass), so the colour mark needs no
// style= attributes, which a strict CSP blocks in server-rendered HTML.
const opacities = [...new Set(gradients.flatMap((g) => g.stops.map((s) => s.opacity)))].filter((o) => o !== undefined);
const stopCss = [
  ...colors.map((_, i) => `.nxm-s-${i + 1}{stop-color:var(--color-brand-mark-${i + 1})}`),
  ...opacities.map((o) => `.nxm-o-${String(o).replace('.', '_')}{stop-opacity:${o}}`),
].join('\n');
const baseCssPath = `${root}../themes/src/base.css`;
const baseCss = readFileSync(baseCssPath, 'utf8');
const block = /(\/\* nexub-mark-stops:start[^*]*\*\/\n)[\s\S]*?(\/\* nexub-mark-stops:end \*\/)/;
if (!block.test(baseCss)) throw new Error('base.css: nexub-mark-stops markers missing');
writeFileSync(baseCssPath, baseCss.replace(block, `$1${stopCss}\n$2`));

// ─── Mono mark: the master's shapes merged into one currentColor path ────────
// One compound path (nonzero) instead of 11 overlapping ones: same silhouette,
// but no anti-aliasing seams where the shapes meet.
const mono = master.replace(
  /<path[\s\S]*<\/defs>/,
  `<path d="${paths.map((p) => p.d).join(' ')}" fill="currentColor"/>`,
);
writeFileSync(`${root}assets/nexub-mark-mono.svg`, mono);

// ─── App tiles ───────────────────────────────────────────────────────────────
const tile = (glyph, halo) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#26282e"/><stop offset="1" stop-color="#050506"/></linearGradient>
    <radialGradient id="sheen" cx=".3" cy=".16" r=".8"><stop offset="0" stop-color="#fff" stop-opacity=".2"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>
    <radialGradient id="halo" cx=".5" cy=".52" r=".42"><stop offset="0" stop-color="${halo}" stop-opacity=".32"/><stop offset="1" stop-color="${halo}" stop-opacity="0"/></radialGradient>
  </defs>
  <rect width="512" height="512" rx="115" fill="url(#tile)"/>
  <rect width="512" height="512" rx="115" fill="url(#halo)"/>
  <rect width="512" height="512" rx="115" fill="url(#sheen)"/>
  <rect x="3" y="3" width="506" height="506" rx="112" fill="none" stroke="#fff" stroke-opacity=".14" stroke-width="6"/>
  ${glyph.replace(/<!--[\s\S]*?-->\s*/g, '').trim()}
</svg>
`;

const png = (svg, size) => sharp(Buffer.from(svg), { density: 72 * (size / 512) * 4 }).resize(size, size).png().toBuffer();

for (const { id, glyph, halo } of PRODUCTS) {
  const name = id ? `app-icon-${id}` : 'app-icon';
  const svg = tile(glyph, halo);
  writeFileSync(`${root}assets/${name}.svg`, svg);
  for (const size of [192, 512]) writeFileSync(`${root}assets/${name}-${size}.png`, await png(svg, size));
}

// favicon.ico: PNG-in-ICO (supported by every current browser).
const icoSizes = [16, 32, 48];
const images = await Promise.all(icoSizes.map((s) => png(tile(MARK_GLYPH, '#8b6cff'), s)));
const header = Buffer.alloc(6 + 16 * images.length);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(images.length, 4);
let offset = header.length;
images.forEach((img, i) => {
  const e = 6 + 16 * i;
  header.writeUInt8(icoSizes[i], e);
  header.writeUInt8(icoSizes[i], e + 1);
  header.writeUInt16LE(1, e + 4);
  header.writeUInt16LE(32, e + 6);
  header.writeUInt32LE(img.length, e + 8);
  header.writeUInt32LE(offset, e + 12);
  offset += img.length;
});
writeFileSync(`${root}assets/favicon.ico`, Buffer.concat([header, ...images]));

console.log(`brand: ${paths.length} paths, ${gradients.length} gradients, ${colors.length} colour tokens`);

function inner(svg) {
  return svg.replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
}
