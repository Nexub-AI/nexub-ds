// build-parts: splits src/core.css into the lean core and one file per component part (12.1).
//
//   src/core-lean.css     core.css without the parts: tokens, resets, focus, motion, density…
//   src/parts/<name>.css  one component part each (aurora, drawer, charts…)
//   src/parts/index.json  per part, the class and data-attribute names that need it
//
// core.css stays the single source: edit it, then run `pnpm --filter @nexub/themes build:parts`.
// Markers: `/*@part <name>*/` … `/*@end*/` (short: core.css counts against its size budget).
// The parts come last in core.css, so core-lean.css followed by every part in index.json order
// is core.css again, rule for rule (the test checks it). An app that loads core-lean plus only
// the parts its components use gets the same cascade for everything it loads.

import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SRC = fileURLToPath(new URL('../src/', import.meta.url));
const PART = /^\/\*@part ([a-z][a-z-]*)\*\/$/;
const END = '/*@end*/';

/** Generic attributes that many components set: they don't say which part a file needs. */
const GENERIC_ATTRS = new Set([
  'data-state',
  'data-side',
  'data-align',
  'data-orientation',
  'data-disabled',
  'data-highlighted',
  'data-placeholder',
  'data-motion',
  'data-material',
  'data-density',
]);

/** Splits core.css text into { lean, parts: [{ name, css }] }. Throws on unbalanced markers. */
export function splitCore(text) {
  const lean = [];
  const parts = [];
  let current = null;
  for (const line of text.split('\n')) {
    const start = PART.exec(line);
    if (start) {
      if (current) throw new Error(`@part ${start[1]} opens inside @part ${current.name}`);
      if (parts.some((p) => p.name === start[1]))
        throw new Error(`@part ${start[1]} appears twice`);
      current = { name: start[1], lines: [] };
    } else if (line === END) {
      if (!current) throw new Error('@end-part without @part');
      parts.push({ name: current.name, css: current.lines.join('\n') + '\n' });
      current = null;
    } else if (current) {
      current.lines.push(line);
    } else {
      lean.push(line);
    }
  }
  if (current) throw new Error(`@part ${current.name} is never closed`);
  return { lean: lean.join('\n').replace(/\n+$/, '\n'), parts };
}

/**
 * When a part is needed: a list of name sets, one per selector (class names and specific data
 * attributes), plus each @keyframes name on its own. The part is needed when every name of one
 * set appears in the code that renders: `.nx-sheen .nx-state-layer` needs nx-sheen as well as the
 * state layer every button has.
 */
export function triggersOf(css) {
  const noComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const sets = new Map();
  const add = (names) => {
    if (!names.length) return;
    const sorted = [...new Set(names)].sort();
    sets.set(sorted.join(' '), sorted);
  };
  // A keyframe is a trigger only when nothing in the part animates with it: then outside code
  // does (LogoWall's animate-[logo-scroll_…] class). Keyframes the part's own rules use are
  // covered by those rules' selectors, and their names can clash with global classes (nx-pop).
  const outsideKeyframes = noComments.replace(
    /@keyframes\s+[\w-]+\s*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g,
    '',
  );
  for (const [, name] of noComments.matchAll(/@keyframes\s+([\w-]+)/g)) {
    if (
      !new RegExp(`animation(-name)?\\s*:[^;]*(^|[^\\w-])${name}($|[^\\w-])`, 'm').test(
        outsideKeyframes,
      )
    )
      add([name]);
  }
  for (const [, prelude] of noComments.matchAll(/([^{}]+)\{/g)) {
    const text = prelude.trim();
    if (text.startsWith('@') || /^(from|to|[\d.]+%)\b/.test(text)) continue;
    for (const selector of text.split(/,(?![^()]*\))/)) {
      const names = [];
      for (const [, cls] of selector.matchAll(/\.([a-zA-Z][\w-]*)/g)) names.push(cls);
      for (const [, attr] of selector.matchAll(/\[(data-[\w-]+)/g))
        if (!GENERIC_ATTRS.has(attr)) names.push(attr);
      add(names);
    }
  }
  return [...sets.values()].sort((a, b) => a.join(' ').localeCompare(b.join(' ')));
}

/** True when `text` (the code an app renders) needs a part with these trigger sets. */
export function needsPart(sets, text) {
  // `_` counts as a boundary: Tailwind writes spaces in arbitrary values as `_` (animate-[logo-scroll_40s…]).
  return sets.some((names) =>
    names.every((n) => new RegExp(`(^|[^A-Za-z0-9-])${n}($|[^A-Za-z0-9-])`).test(text)),
  );
}

const header = (what) =>
  `/* GENERATED by packages/themes/scripts/build-parts.mjs from core.css. Do not edit:\n   change core.css and run \`pnpm --filter @nexub/themes build:parts\`. ${what} */\n`;

/** The files build-parts writes, as { path relative to src/: contents }. */
export function render(text) {
  const { lean, parts } = splitCore(text);
  const files = {
    'core-lean.css': header('core.css without its component parts (12.1).') + lean,
  };
  const index = {};
  for (const p of parts) {
    files[`parts/${p.name}.css`] = header(`Part "${p.name}".`) + p.css;
    index[p.name] = triggersOf(p.css);
  }
  files['parts/index.json'] =
    JSON.stringify({ order: parts.map((p) => p.name), triggers: index }, null, 2) + '\n';
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = render(readFileSync(SRC + 'core.css', 'utf8'));
  rmSync(SRC + 'parts', { recursive: true, force: true });
  mkdirSync(SRC + 'parts', { recursive: true });
  for (const [path, contents] of Object.entries(files)) writeFileSync(SRC + path, contents);
  console.log(`build-parts: core-lean.css and ${readdirSync(SRC + 'parts').length - 1} parts`);
}
