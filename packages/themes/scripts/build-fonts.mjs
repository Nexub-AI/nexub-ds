// Builds src/fonts.css + src/fonts/ from @fontsource-variable/plus-jakarta-sans.
//
// Why not import Fontsource's CSS directly: bundlers inline small assets as
// data: URLs (Vite under 4 KB, webpack under 8 KB), and a strict CSP
// (`font-src 'self'`) blocks data: fonts. So we ship only the subsets whose
// files are above both limits, which bundlers always emit as real files. The
// one subset dropped (cyrillic-ext, ~1.7 KB, a few rare glyphs such as ₴)
// falls back to the system font.
//
// Run after upgrading Fontsource: pnpm --filter @nexub/themes build:fonts
import { copyFileSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const MIN_BYTES = 8 * 1024; // webpack's default inline limit (Vite's is 4 KB)

const require = createRequire(import.meta.url);
const pkg = dirname(require.resolve('@fontsource-variable/plus-jakarta-sans/package.json'));
const out = new URL('../src/', import.meta.url);
const fontsDir = new URL('fonts/', out);

rmSync(fontsDir, { recursive: true, force: true });
mkdirSync(fontsDir);
copyFileSync(join(pkg, 'LICENSE'), new URL('LICENSE', fontsDir));

const faces = [];
const dropped = [];
for (const css of ['wght.css', 'wght-italic.css']) {
  for (const face of readFileSync(join(pkg, css), 'utf8').match(/\/\*[^*]*\*\/\s*@font-face\s*{[^}]*}/g)) {
    const file = /url\(\.\/files\/([^)]+)\)/.exec(face)[1];
    if (statSync(join(pkg, 'files', file)).size < MIN_BYTES) {
      dropped.push(file);
      continue;
    }
    copyFileSync(join(pkg, 'files', file), new URL(file, fontsDir));
    faces.push(face.replace('./files/', './fonts/'));
  }
}

const { version } = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'));
writeFileSync(
  new URL('fonts.css', out),
  `/* @nexub/themes — fonts.css. GENERATED by scripts/build-fonts.mjs, do not edit.
   Plus Jakarta Sans (OFL-1.1, see fonts/LICENSE) from
   @fontsource-variable/plus-jakarta-sans@${version}. Every file is over ${MIN_BYTES} bytes so
   bundlers emit it as a file instead of inlining a data: URL (strict-CSP safe).
   Left out: ${dropped.join(', ')}. */

${faces.join('\n\n')}
`,
);
console.log(`fonts.css: ${faces.length} faces, dropped ${dropped.length} (${dropped.join(', ')})`);
