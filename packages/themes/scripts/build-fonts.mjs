// Builds src/fonts.css + src/fonts/ from Fontsource: Inter (UI face, with the
// optical-size axis) and Plus Jakarta Sans (display face).
//
// Why not import Fontsource's CSS directly: bundlers inline small assets as
// data: URLs (Vite under 4 KB, webpack under 8 KB), and a strict CSP
// (`font-src 'self'`) blocks data: fonts. So we ship only the subsets whose
// files are above both limits, which bundlers always emit as real files. The
// few tiny subsets dropped (listed in fonts.css) fall back to the system font.
//
// Run after upgrading Fontsource: pnpm --filter @nexub/themes build:fonts
import { copyFileSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const MIN_BYTES = 8 * 1024; // webpack's default inline limit (Vite's is 4 KB)

const SOURCES = [
  { name: 'inter', pkg: '@fontsource-variable/inter', css: ['opsz.css', 'opsz-italic.css'] },
  { name: 'plus-jakarta-sans', pkg: '@fontsource-variable/plus-jakarta-sans', css: ['wght.css', 'wght-italic.css'] },
];

const require = createRequire(import.meta.url);
const out = new URL('../src/', import.meta.url);
const fontsDir = new URL('fonts/', out);

rmSync(fontsDir, { recursive: true, force: true });
mkdirSync(fontsDir);

const faces = [];
const dropped = [];
const credits = [];
for (const { name, pkg: id, css } of SOURCES) {
  const pkg = dirname(require.resolve(`${id}/package.json`));
  copyFileSync(join(pkg, 'LICENSE'), new URL(`LICENSE-${name}`, fontsDir));
  credits.push(`${id}@${JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8')).version}`);
  for (const file of css) {
    for (const face of readFileSync(join(pkg, file), 'utf8').match(/\/\*[^*]*\*\/\s*@font-face\s*{[^}]*}/g)) {
      const font = /url\(\.\/files\/([^)]+)\)/.exec(face)[1];
      if (statSync(join(pkg, 'files', font)).size < MIN_BYTES) {
        dropped.push(font);
        continue;
      }
      copyFileSync(join(pkg, 'files', font), new URL(font, fontsDir));
      faces.push(face.replace('./files/', './fonts/'));
    }
  }
}

writeFileSync(
  new URL('fonts.css', out),
  `/* @nexub/themes — fonts.css. GENERATED by scripts/build-fonts.mjs, do not edit.
   Inter + Plus Jakarta Sans (OFL-1.1, see fonts/LICENSE-*) from
   ${credits.join(', ')}. Every file is over ${MIN_BYTES} bytes so
   bundlers emit it as a file instead of inlining a data: URL (strict-CSP safe).
   Left out: ${dropped.join(', ') || 'none'}. */

${faces.join('\n\n')}
`,
);
console.log(`fonts.css: ${faces.length} faces, dropped ${dropped.length} (${dropped.join(', ')})`);
