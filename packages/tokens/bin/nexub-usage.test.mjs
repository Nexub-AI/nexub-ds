import { test } from 'node:test';
import assert from 'node:assert/strict';
import { scanSource, cssPlan, renderCss, pruneCss } from './nexub-usage.mjs';

test('reads named, aliased, type and multi-line @nexub imports; ignores others', () => {
  const src = `
    import { Button, Card as Panel } from '@nexub/react';
    import type { Size } from "@nexub/react";
    import {
      AuthCard,
      type PlanCardProps,
    } from '@nexub/patterns';
    import { useState } from 'react';
  `;
  assert.deepEqual(scanSource(src), [
    { pkg: '@nexub/react', name: 'Button' },
    { pkg: '@nexub/react', name: 'Card' },
    { pkg: '@nexub/react', name: 'Size' },
    { pkg: '@nexub/patterns', name: 'AuthCard' },
    { pkg: '@nexub/patterns', name: 'PlanCardProps' },
  ]);
});

const manifests = {
  '@nexub/react': {
    exports: { Button: 'components/Button/index.js', Aurora: 'components/Aurora/index.js' },
    modules: {
      'components/Button/index.js': { deps: ['components/Button/Button.js'] },
      'components/Button/Button.js': { deps: ['utils/cn.js'], parts: ['micro'] },
      'components/Aurora/index.js': { deps: ['components/Aurora/Aurora.js'] },
      'components/Aurora/Aurora.js': { deps: ['utils/cn.js'], parts: ['aurora'] },
      'utils/cn.js': { deps: [] },
    },
  },
  '@nexub/patterns': {
    exports: { AuthCard: 'AuthCard/AuthCard.js' },
    modules: { 'AuthCard/AuthCard.js': { deps: [], nexub: { '@nexub/react': ['Button'] } } },
  },
};
const parts = {
  order: ['stagger', 'micro', 'aurora'],
  triggers: { stagger: [['nx-stagger']], micro: [], aurora: [] },
};

test('cssPlan: only the modules and parts the imports reach, across packages', () => {
  const plan = cssPlan({
    imports: [
      { pkg: '@nexub/patterns', name: 'AuthCard' },
      { pkg: '@nexub/react', name: 'ButtonProps' },
    ],
    appText: '<ul className="nx-stagger">',
    manifests,
    parts,
  });
  assert.deepEqual(plan.parts, ['stagger', 'micro']);
  assert.deepEqual(plan.files, {
    '@nexub/patterns': ['AuthCard/AuthCard.js'],
    '@nexub/react': ['components/Button/Button.js', 'components/Button/index.js', 'utils/cn.js'],
  });
  assert.deepEqual(plan.unknown, ['@nexub/react ButtonProps']);
});

test('renderCss: part imports in order, then @source paths relative to the output file', () => {
  const plan = { parts: ['micro'], files: { '@nexub/react': ['utils/cn.js'] }, unknown: [] };
  const css = renderCss(plan, {
    outFile: '/app/src/nexub.css',
    distDirs: { '@nexub/react': '/app/node_modules/@nexub/react/dist' },
    command: 'nexub-usage src --css src/nexub.css',
  });
  assert.match(css, /^\/\* GENERATED by `nexub-usage src --css src\/nexub.css`/);
  assert.ok(css.includes("@import '@nexub/themes/parts/micro.css' layer(base);\n"));
  assert.ok(css.endsWith('@source "../node_modules/@nexub/react/dist/utils/cn.js";\n'));
});

test('pruneCss: drops unused Nexub variables only, keeps what CSS, code, values and prefixes use', () => {
  const css =
    ':root{--color-a:red;--color-b:var(--color-c);--color-c:blue;--color-unused:pink;--motion-spring-fast:1s;--app-own:1px}' +
    '.x{color:var(--color-b)}';
  const code = 'el.style.setProperty("--color-a", v); const d = `var(--motion-spring-${speed})`;';
  const names = new Set([
    '--color-a',
    '--color-b',
    '--color-c',
    '--color-unused',
    '--motion-spring-fast',
  ]);
  const { css: out, removed } = pruneCss(css, code, names);
  assert.equal(removed, 1);
  assert.equal(
    out,
    ':root{--color-a:red;--color-b:var(--color-c);--color-c:blue;--motion-spring-fast:1s;--app-own:1px}.x{color:var(--color-b)}',
  );
});

test('pruneCss: a last declaration without a semicolon is removed cleanly', () => {
  const { css } = pruneCss(':root{--a:1;--b:2}.y{z:var(--a)}', '', new Set(['--a', '--b']));
  assert.equal(css, ':root{--a:1;}.y{z:var(--a)}');
});

test('pruneCss: a quoted prefix in concatenation keeps the family; a name only from data does not', () => {
  const css = ':root{--color-red:1;--color-blue:2;--size-a:3}';
  const names = new Set(['--color-red', '--color-blue', '--size-a']);
  assert.equal(pruneCss(css, "el.style.setProperty('--color-' + tone, v)", names).removed, 1);
  assert.equal(pruneCss(css, "el.style.setProperty('--' + name, v)", names).removed, 3);
});
