// Native platform outputs (R3): the tokens as Swift (SwiftUI) and Kotlin
// (Jetpack Compose) source, from the same resolved values as
// @nexub/tokens/native. One colour scheme per scheme × contrast level; spacing,
// radius, shape and sizes in points / dp; the type scale as size, line height,
// weight and tracking.
//
//   @nexub/tokens/swift/NexubTokens.swift
//   @nexub/tokens/compose/NexubTokens.kt

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
/** `2xl` → `radius2xl`, `0-5` → `space0_5`, `md` → `radiusMd`. Valid in Swift and Kotlin. */
export const ident = (prefix, key) => prefix + pascal(String(key).replace(/^(\d+)-(\d+)$/, '$1_$2'));
const LEVEL = { standard: '', medium: 'MediumContrast', high: 'HighContrast' };
const hex = (h) => h.replace('#', '').toUpperCase();

function schemes(native) {
  const out = [];
  for (const [level, s] of Object.entries(native.color.roles))
    for (const scheme of ['light', 'dark']) out.push({ name: `${scheme}${LEVEL[level]}`, roles: s[scheme] });
  return out;
}
const groups = (native) => [
  ['space', native.spacing],
  ['radius', native.radius],
  ['shape', native.shape],
  ...Object.entries(native.size).map(([k, v]) => [camel(k), v]),
];

export function swift(native) {
  const all = schemes(native);
  const roles = Object.keys(all[0].roles);
  const rgb = (h) => {
    const n = parseInt(hex(h), 16);
    return `Color(red: ${((n >> 16) & 255) / 255}, green: ${((n >> 8) & 255) / 255}, blue: ${(n & 255) / 255})`;
  };
  return [
    '// Auto-generated by @nexub/tokens. Do not edit.',
    'import SwiftUI',
    '',
    '/// Nexub colour roles for one scheme and contrast level. Pair every background with its `on` role.',
    'public struct NexubColors: Sendable {',
    ...roles.map((r) => `    public let ${camel(r)}: Color`),
    '}',
    '',
    'public enum NexubTokens {',
    ...all.map((s) => `    public static let ${s.name} = NexubColors(${roles.map((r) => `${camel(r)}: ${rgb(s.roles[r])}`).join(', ')})`),
    '',
    ...groups(native).flatMap(([prefix, obj]) =>
      Object.entries(obj).map(([k, v]) => `    public static let ${ident(prefix, k)}: CGFloat = ${v}`),
    ),
    '',
    '    public struct TypeStyle: Sendable { public let size: CGFloat; public let lineHeight: CGFloat; public let weight: Int; public let tracking: CGFloat }',
    ...Object.entries(native.type).map(
      ([role, v]) => `    public static let ${ident('type', role)} = TypeStyle(size: ${v.size}, lineHeight: ${v.lineHeight}, weight: ${v.weight}, tracking: ${v.letterSpacing})`,
    ),
    '}',
    '',
  ].join('\n');
}

export function compose(native) {
  const all = schemes(native);
  const roles = Object.keys(all[0].roles);
  return [
    '// Auto-generated by @nexub/tokens. Do not edit.',
    'package com.nexub.tokens',
    '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.sp',
    '',
    '/** Nexub colour roles for one scheme and contrast level. Pair every background with its `on` role. */',
    'data class NexubColors(',
    ...roles.map((r) => `    val ${camel(r)}: Color,`),
    ')',
    '',
    'data class NexubTypeStyle(val size: androidx.compose.ui.unit.TextUnit, val lineHeight: androidx.compose.ui.unit.TextUnit, val weight: Int, val tracking: androidx.compose.ui.unit.TextUnit)',
    '',
    'object NexubTokens {',
    ...all.map((s) => `    val ${s.name} = NexubColors(${roles.map((r) => `${camel(r)} = Color(0xFF${hex(s.roles[r])})`).join(', ')})`),
    '',
    ...groups(native).flatMap(([prefix, obj]) => Object.entries(obj).map(([k, v]) => `    val ${ident(prefix, k)} = ${v}.dp`)),
    '',
    ...Object.entries(native.type).map(
      ([role, v]) => `    val ${ident('type', role)} = NexubTypeStyle(${v.size}.sp, ${v.lineHeight}.sp, ${v.weight}, (${v.letterSpacing}).sp)`,
    ),
    '}',
    '',
  ].join('\n');
}
