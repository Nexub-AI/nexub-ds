import StyleDictionary from 'style-dictionary';
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

// ─── Custom transforms ───────────────────────────────────────────────────────

StyleDictionary.registerTransform({
  name: 'name/kebab-deep',
  type: 'name',
  transform(token) {
    return token.path.join('-');
  },
});

// ─── Custom formats ──────────────────────────────────────────────────────────

StyleDictionary.registerFormat({
  name: 'typescript/tokens-const',
  format({ dictionary }) {
    const nested = buildNested(dictionary.allTokens);
    return [
      `// Auto-generated by @nexub/tokens build script. Do not edit manually.`,
      `/* eslint-disable */`,
      `export const tokens = ${JSON.stringify(nested, null, 2)} as const;`,
      `export type Tokens = typeof tokens;`,
    ].join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'json/flat',
  format({ dictionary }) {
    const flat = {};
    for (const token of dictionary.allTokens) {
      flat[token.path.join('.')] = token.$value ?? token.value;
    }
    return JSON.stringify(flat, null, 2);
  },
});

StyleDictionary.registerFormat({
  name: 'tailwind/preset',
  format({ dictionary }) {
    const colors = {};
    const spacing = {};
    const borderRadius = {};
    const boxShadow = {};
    const zIndex = {};
    const fontFamily = {};

    for (const token of dictionary.allTokens) {
      const [ns, ...rest] = token.path;
      const varName = `--${token.path.join('-')}`;

      if (ns === 'color') {
        setDeep(colors, rest, `var(${varName})`);
      } else if (ns === 'spacing' || ns === 'container') {
        const key = ns === 'container' ? `container-${rest.join('-')}` : rest.join('-');
        spacing[key] = `var(${varName})`;
      } else if (ns === 'radius') {
        borderRadius[rest.join('-')] = `var(${varName})`;
      } else if (ns === 'shadow') {
        boxShadow[rest.join('-')] = `var(${varName})`;
      } else if (ns === 'z') {
        zIndex[rest.join('-')] = `var(${varName})`;
      } else if (ns === 'font' && rest[0] === 'family') {
        fontFamily[rest[1]] = `var(${varName})`;
      }
    }

    const preset = {
      theme: {
        extend: {
          colors,
          spacing,
          borderRadius,
          boxShadow,
          zIndex,
          fontFamily,
        },
      },
    };

    return [
      `// Auto-generated by @nexub/tokens build script. Do not edit.`,
      `const preset = ${JSON.stringify(preset, null, 2)};`,
      `export default preset;`,
    ].join('\n');
  },
});

// ─── Helpers ─────────────────────────────────────────────────────────────────

function buildNested(tokens) {
  const result = {};
  for (const token of tokens) {
    setDeep(result, token.path, token.$value ?? token.value);
  }
  return result;
}

function setDeep(obj, path, value) {
  let cur = obj;
  for (let i = 0; i < path.length - 1; i++) {
    const key = path[i];
    if (!cur[key] || typeof cur[key] !== 'object') cur[key] = {};
    cur = cur[key];
  }
  cur[path[path.length - 1]] = value;
}

// ─── Build ───────────────────────────────────────────────────────────────────

const sd = new StyleDictionary({
  source: [`${root}/tokens/*.json`],
  platforms: {
    css: {
      transformGroup: 'css',
      transforms: ['name/kebab-deep'],
      prefix: '',
      buildPath: `${root}/dist/css/`,
      files: [
        {
          destination: 'variables.css',
          format: 'css/variables',
          options: { selector: ':root', outputReferences: false },
        },
      ],
    },
    ts: {
      transformGroup: 'js',
      transforms: ['name/kebab-deep'],
      buildPath: `${root}/src/generated/`,
      files: [
        {
          destination: 'tokens.ts',
          format: 'typescript/tokens-const',
        },
      ],
    },
    json: {
      transformGroup: 'js',
      transforms: ['name/kebab-deep'],
      buildPath: `${root}/dist/json/`,
      files: [
        {
          destination: 'tokens.json',
          format: 'json/flat',
        },
      ],
    },
    tailwind: {
      transformGroup: 'js',
      transforms: ['name/kebab-deep'],
      buildPath: `${root}/dist/tailwind/`,
      files: [
        {
          destination: 'preset.js',
          format: 'tailwind/preset',
        },
      ],
    },
  },
});

await sd.buildAllPlatforms();

// Emit stub CSS files for light/dark — Phase 2 fills them in
mkdirSync(`${root}/dist/css`, { recursive: true });
writeFileSync(
  `${root}/dist/css/light.css`,
  `/* Light mode token overrides — filled in by @nexub/themes in Phase 2. */\n@import './variables.css';\n`,
);
writeFileSync(
  `${root}/dist/css/dark.css`,
  `/* Dark mode token overrides — filled in by @nexub/themes in Phase 2. */\n`,
);

// Emit tailwind preset type declaration
mkdirSync(`${root}/dist/tailwind`, { recursive: true });
writeFileSync(
  `${root}/dist/tailwind/preset.d.ts`,
  `import type { Config } from 'tailwindcss';\ndeclare const preset: Config;\nexport default preset;\n`,
);

console.log('✓ @nexub/tokens built successfully.');
